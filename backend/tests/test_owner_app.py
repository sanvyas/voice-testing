    t = client.get(f"{API}/thread", params={"phone": "+919876543210"}).json()
    assert [i["sender"] for i in t["items"] if i["type"] == "wa"] == ["owner"] and t["resolved"] and t["pending"] == []
    assert client.get(f"{API}/calls/{cid}").json()["reviewed"] is True


